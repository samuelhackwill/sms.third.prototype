import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {envelope} from '../../../protocol/core.mjs';
import {createController} from '../app.mjs';
import {SimulatedClient} from '../simulated-client.mjs';

async function until(predicate){
  const deadline=Date.now()+6000;
  while(Date.now()<deadline){if(await predicate())return;await new Promise(resolve=>setTimeout(resolve,20));}
  throw new Error('cycle timed out');
}

test('cycle switches through web transition and counts each completed kiss once',async t=>{
  const directory=await mkdtemp(join(tmpdir(),'wall-cycle-'));
  const key='cycle-operator-secret-0000000000000000';
  const server=await createController({dataDir:directory,adminToken:key,kissingOptions:{fetchImpl:async()=>{throw new Error('offline');}},fullFrameOptions:{probe:()=>({width:375,height:667,durationMs:1000})}});
  await server.app.listen({host:'127.0.0.1',port:0});
  const endpoint=`ws://127.0.0.1:${server.app.server.address().port}/phone-wall/ws`;
  const clients=[new SimulatedClient(endpoint),new SimulatedClient(endpoint)];
  t.after(async()=>{clients.forEach(client=>client.stop());await server.app.close();await rm(directory,{recursive:true,force:true});});
  clients.forEach(client=>client.connect());
  await until(()=>clients.every(client=>client.welcome));
  const state=server.store.current();
  state.mode='exhibition';state.layout.rows=2;state.layout.columns=1;
  state.layout.slots=clients.map((client,index)=>({deviceId:client.identity.deviceId,slotIndex:index,geometry:{x:0,y:index*667,width:375,height:667}}));
  const headers={authorization:`Bearer ${key}`};
  const action=async payload=>{
    const result=await server.app.inject({url:'/phone-wall/api',method:'POST',headers,payload});
    assert.equal(result.statusCode,200,result.body);
    return result.json();
  };
  const status=async()=>server.app.inject({url:'/phone-wall/api',headers}).then(response=>response.json());
  await action({action:'configure',config:state,expectedRevision:state.revision});
  const clip={source:'https://sms-clips.samuel.ovh/test.mp4',hash:'a'.repeat(64),bytes:1000,startSec:null,endSec:null};
  server.store.db.prepare('INSERT INTO kissing_clips(source,hash,data,added) VALUES(?,?,?,?)').run(clip.source,clip.hash,JSON.stringify(clip),Date.now());
  server.store.db.prepare('INSERT INTO assets VALUES(?,?,?)').run(clip.hash,'video/mp4',clip.bytes);
  server.ticker.setCuratedSecond(true);
  server.ticker.startCurated(['1234567890','HELLO']);
  const settings={curatedDurationSec:10,kissingMetric:'count',kissingDurationSec:10,kissTarget:1,fullFrameKissTarget:1};
  await action({action:'cycle.start',settings});
  await until(()=>clients.every(client=>server.releases.snapshot(client.identity.deviceId).active?.release.definition.artworkId==='live-ticker'&&client.activeArtwork));
  await until(()=>server.ticker.runs().length===2);
  server.cycleTick(Date.now()+11000);
  assert.equal((await status()).cycle.phase,'draining-curated');
  assert.equal(server.ticker.runs().length,1);
  server.cycleTick();
  assert.equal((await status()).cycle.phase,'draining-curated');
  const textRun=server.ticker.runs()[0],textPhone=clients.find(client=>client.identity.deviceId===textRun.targets[0]);
  server.ticker.acknowledge(textPhone.identity.deviceId,{type:'ticker.ready',runId:textRun.id,width:100});
  server.ticker.acknowledge(textPhone.identity.deviceId,{type:'ticker.done',runId:textRun.id},Date.now()+1000000);
  server.cycleTick();
  await until(async()=>['transition-to-kissing','kissing'].includes((await status()).cycle.phase));
  assert.equal(new Set((await status()).transition.active.rows.map(row=>row.color)).size,2);
  server.cycleTick(Date.now()+20000);
  assert.equal((await status()).cycle.phase,'kissing');
  const send=(client,kind)=>client.ws.send(JSON.stringify(envelope('kissing.status',{status:kind,hash:clip.hash})));
  send(clients[0],'playing');send(clients[0],'ended');send(clients[0],'ended');
  await until(async()=>(await status()).cycle.phase==='draining-kissing');
  assert.equal((await status()).kissing.enabled,true);
  send(clients[0],'drained');
  await new Promise(resolve=>setTimeout(resolve,50));
  assert.equal((await status()).cycle.phase,'draining-kissing');
  send(clients[1],'drained');
  await until(async()=>['preparing-barthes','transition-to-barthes'].includes((await status()).cycle.phase));
  assert.equal((await status()).cycle.kisses,1);
  await until(async()=>((await status()).cycle.phase==='transition-to-barthes'));
  server.cycleTick(Date.now()+30000);
  assert.equal((await status()).cycle.phase,'barthes');
  const chapter=(await status()).cycle;
  assert.equal(chapter.barthesChapter,'Comment est fait ce livre');
  assert.ok(chapter.barthesChapterCount>1);
  await until(()=>server.ticker.runs().some(run=>run.source==='barthes'));
  const barthesRuns=server.ticker.runs().filter(run=>run.source==='barthes');
  const complete=server.store.db.prepare("INSERT INTO ticker_messages(external_id,text,source,status) VALUES(?,'test','barthes','completed')");
  for(let index=barthesRuns.length;index<chapter.barthesChapterCount;index++)complete.run(`cycle-test-completed-${index}`);
  for(const run of barthesRuns)for(const id of run.targets){server.ticker.acknowledge(id,{type:'ticker.ready',runId:run.id,width:100});server.ticker.acknowledge(id,{type:'ticker.done',runId:run.id},Date.now()+1000000);}
  server.cycleTick();
  assert.equal((await status()).cycle.phase,'draining-barthes');
  server.cycleTick();
  await until(async()=>((await status()).cycle.phase==='transition-to-full-frame'));
  server.cycleTick(Date.now()+30000);
  assert.equal((await status()).cycle.phase,'full-frame');
  await until(()=>server.fullFrame.state.playedCount===1);
  server.cycleTick(Date.now()+5000);
  await until(async()=>((await status()).cycle.phase==='transition-to-curated'));
  server.cycleTick(Date.now()+30000);
  assert.equal((await status()).cycle.phase,'curated');
  assert.equal((await status()).kissing.enabled,false);
  await action({action:'audio.volume',volume:0.37});
  await until(()=>clients.every(client=>client.state?.audioVolume===0.37));
  assert.equal((await status()).state.audioVolume,0.37);
  clients[1].stop();
  await until(()=>!server.sessions.has(clients[1].identity.deviceId));
  const remote=await server.app.inject({url:'/phone-wall/remote/status',headers}).then(response=>response.json());
  assert.equal(remote.devices.find(device=>device._id===clients[1].identity.deviceId).connected,false);
  assert.equal(remote.state.layout.slots.length,2);
  assert.ok(Object.hasOwn(remote.system,'controllerCpuPercent'));
  server.cycleTick();
  assert.equal((await status()).cycle.enabled,true);
  await action({action:'remote.night'});
  assert.equal((await status()).cycle.enabled,false);
  assert.equal((await status()).state.mode,'night');
  assert.equal((await status()).state.nightBrightness,0);
  await action({action:'cycle.settings',settings:{...settings,barthesMetric:'lines',barthesLineTarget:7}});
  assert.equal((await status()).cycle.barthesMetric,'lines');
  assert.equal((await status()).cycle.barthesLineTarget,7);
  await action({action:'remote.day'});
  assert.equal((await status()).cycle.enabled,true);
  assert.equal((await status()).cycle.phase,'curated');
  assert.equal((await status()).state.brightness,1);
});
